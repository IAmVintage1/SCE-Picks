import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
const anonKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

const manifestPath = path.join(process.cwd(), "lib", "generatedPlayerImages.ts");
const publicDir = path.join(process.cwd(), "public", "players");

function normalizePlayerName(value) {
  return String(value ?? "")
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[’']/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

function slugify(value) {
  return normalizePlayerName(value).replace(/\s+/g, "-") || "player";
}

function extensionFromType(contentType, sourceUrl) {
  const type = String(contentType ?? "").toLowerCase();
  if (type.includes("png")) return "png";
  if (type.includes("webp")) return "webp";
  if (type.includes("jpeg") || type.includes("jpg")) return "jpg";

  try {
    const pathname = new URL(sourceUrl).pathname.toLowerCase();
    const match = pathname.match(/\.(png|webp|jpe?g)$/);
    if (match) return match[1] === "jpeg" ? "jpg" : match[1];
  } catch {}

  return "png";
}

async function writeManifest(entries) {
  const sorted = Object.fromEntries(
    Object.entries(entries).sort(([a], [b]) => a.localeCompare(b)),
  );

  const contents = [
    "// Auto-generated by scripts/cache-player-images.mjs before production builds.",
    `export const GENERATED_PLAYER_IMAGES: Record<string, string> = ${JSON.stringify(sorted, null, 2)};`,
    "",
  ].join("\n");

  await writeFile(manifestPath, contents, "utf8");
}

if (!supabaseUrl || !anonKey) {
  console.warn("[player-cache] Supabase env vars are missing; keeping remote image fallbacks.");
  await writeManifest({});
  process.exit(0);
}

await mkdir(publicDir, { recursive: true });

const playersResponse = await fetch(
  `${supabaseUrl}/rest/v1/players?select=name,image_url&active=eq.true`,
  {
    headers: {
      apikey: anonKey,
      Authorization: `Bearer ${anonKey}`,
    },
  },
);

if (!playersResponse.ok) {
  console.warn(
    `[player-cache] Could not read players (${playersResponse.status}); keeping remote fallbacks.`,
  );
  await writeManifest({});
  process.exit(0);
}

const players = await playersResponse.json();
const manifest = {};
let cached = 0;

for (const player of players) {
  const name = String(player?.name ?? "").trim();
  const imageUrl = String(player?.image_url ?? "").trim();
  if (!name || !imageUrl) continue;

  try {
    const imageResponse = await fetch(imageUrl, { cache: "no-store" });
    if (!imageResponse.ok) {
      console.warn(`[player-cache] ${name}: ${imageResponse.status}`);
      continue;
    }

    const bytes = Buffer.from(await imageResponse.arrayBuffer());
    const extension = extensionFromType(
      imageResponse.headers.get("content-type"),
      imageUrl,
    );
    const filename = `${slugify(name)}.${extension}`;

    await writeFile(path.join(publicDir, filename), bytes);
    manifest[normalizePlayerName(name)] = `/players/${filename}`;
    cached += 1;
  } catch (error) {
    console.warn(`[player-cache] ${name}: ${error instanceof Error ? error.message : error}`);
  }
}

await writeManifest(manifest);
console.log(`[player-cache] Cached ${cached} player images locally for this deployment.`);
