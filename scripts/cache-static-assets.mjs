import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
const anonKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

const playerManifestPath = path.join(process.cwd(), "lib", "generatedPlayerImages.ts");
const teamManifestPath = path.join(process.cwd(), "lib", "generatedTeamImages.ts");
const playerDir = path.join(process.cwd(), "public", "players");
const teamDir = path.join(process.cwd(), "public", "teams");

function normalizeName(value) {
  return String(value ?? "")
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[’']/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

function slugify(value) {
  return normalizeName(value).replace(/\s+/g, "-") || "asset";
}

function extensionFromType(contentType, sourceUrl) {
  const type = String(contentType ?? "").toLowerCase();
  if (type.includes("webp")) return "webp";
  if (type.includes("png")) return "png";
  if (type.includes("jpeg") || type.includes("jpg")) return "jpg";
  if (type.includes("avif")) return "avif";

  try {
    const pathname = new URL(sourceUrl).pathname.toLowerCase();
    const match = pathname.match(/\.(png|webp|avif|jpe?g)$/);
    if (match) return match[1] === "jpeg" ? "jpg" : match[1];
  } catch {}

  return "png";
}

async function writePlayerManifest(entries) {
  const sorted = Object.fromEntries(
    Object.entries(entries).sort(([a], [b]) => a.localeCompare(b)),
  );
  await writeFile(
    playerManifestPath,
    `// Auto-generated by scripts/cache-static-assets.mjs before production builds.\nexport const GENERATED_PLAYER_IMAGES: Record<string, string> = ${JSON.stringify(sorted, null, 2)};\n`,
    "utf8",
  );
}

async function writeTeamManifest(entries) {
  await writeFile(
    teamManifestPath,
    `// Auto-generated by scripts/cache-static-assets.mjs before production builds.\nexport const GENERATED_TEAM_IMAGES: Record<string, string> = ${JSON.stringify(entries, null, 2)};\n`,
    "utf8",
  );
}

async function cacheAsset(sourceUrl, destinationDir, basename) {
  const response = await fetch(sourceUrl, { cache: "no-store" });
  if (!response.ok) {
    throw new Error(`image request returned ${response.status}`);
  }

  const bytes = Buffer.from(await response.arrayBuffer());
  const extension = extensionFromType(response.headers.get("content-type"), sourceUrl);
  const digest = createHash("sha1").update(bytes).digest("hex").slice(0, 10);
  const filename = `${slugify(basename)}-${digest}.${extension}`;
  await writeFile(path.join(destinationDir, filename), bytes);
  return filename;
}

await mkdir(playerDir, { recursive: true });
await mkdir(teamDir, { recursive: true });

if (!supabaseUrl || !anonKey) {
  console.warn("[static-assets] Supabase env vars missing; remote fallbacks will be used.");
  await writePlayerManifest({});
  await writeTeamManifest({});
  process.exit(0);
}

const headers = {
  apikey: anonKey,
  Authorization: `Bearer ${anonKey}`,
};

const playerManifest = {};
let playerCount = 0;

try {
  const response = await fetch(
    `${supabaseUrl}/rest/v1/players?select=name,image_url&active=eq.true`,
    { headers },
  );

  if (!response.ok) {
    throw new Error(`player query returned ${response.status}`);
  }

  const players = await response.json();

  for (const player of players) {
    const name = String(player?.name ?? "").trim();
    const imageUrl = String(player?.image_url ?? "").trim();
    if (!name || !imageUrl) continue;

    try {
      const filename = await cacheAsset(imageUrl, playerDir, name);
      playerManifest[normalizeName(name)] = `/players/${filename}`;
      playerCount += 1;
    } catch (error) {
      console.warn(`[static-assets] ${name}: ${error instanceof Error ? error.message : error}`);
    }
  }
} catch (error) {
  console.warn(`[static-assets] Player cache failed: ${error instanceof Error ? error.message : error}`);
}

await writePlayerManifest(playerManifest);

const teamManifest = {};

try {
  const response = await fetch(
    `${supabaseUrl}/rest/v1/event_settings?select=young_logo_url,alum_logo_url&id=eq.1&limit=1`,
    { headers },
  );

  if (!response.ok) {
    throw new Error(`event settings query returned ${response.status}`);
  }

  const [settings] = await response.json();
  const logoEntries = [
    ["youngknights", settings?.young_logo_url],
    ["alumknights", settings?.alum_logo_url],
  ];

  for (const [team, rawUrl] of logoEntries) {
    const imageUrl = String(rawUrl ?? "").trim();
    if (!imageUrl) continue;

    try {
      const filename = await cacheAsset(imageUrl, teamDir, team);
      teamManifest[team] = `/teams/${filename}`;
    } catch (error) {
      console.warn(`[static-assets] ${team}: ${error instanceof Error ? error.message : error}`);
    }
  }
} catch (error) {
  console.warn(`[static-assets] Team logo cache failed: ${error instanceof Error ? error.message : error}`);
}

await writeTeamManifest(teamManifest);
console.log(
  `[static-assets] Cached ${playerCount} player images and ${Object.keys(teamManifest).length} team logos as direct static assets.`,
);
